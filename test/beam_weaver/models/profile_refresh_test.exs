defmodule BeamWeaver.Models.ProfileRefreshTest do
  use ExUnit.Case, async: true

  alias BeamWeaver.Models.ProfileRefresh

  @moduletag :tmp_dir

  test "refresh aborts when user declines an external output directory", %{tmp_dir: tmp_dir} do
    root = Path.join(tmp_dir, "root")
    data_dir = Path.join([tmp_dir, "external", "data"])

    assert {:error, error} =
             ProfileRefresh.refresh("anthropic", data_dir,
               cwd: root,
               source_data: source_data(),
               confirm_fun: fn _target, _cwd -> false end
             )

    assert error.type == :aborted
    refute File.exists?(Path.join(data_dir, "profiles.json"))
  end

  test "refresh writes BeamWeaver profile JSON from source data", %{tmp_dir: data_dir} do
    assert {:ok, %{path: path, profiles: [%{id: "fixture-model"}]}} =
             ProfileRefresh.refresh("anthropic", data_dir, source_data: source_data(), force: true)

    assert path == Path.join(data_dir, "profiles.json")

    assert {:ok, artifact} = path |> File.read!() |> BeamWeaver.JSON.decode()
    assert artifact["provider"] == "anthropic"
    assert artifact["admonition"] =~ "DO NOT EDIT THIS FILE MANUALLY"
    assert [%{"id" => "fixture-model", "provider" => "anthropic", "image_inputs" => true}] = artifact["profiles"]
  end

  test "refresh fails without writing when provider is absent", %{tmp_dir: data_dir} do
    assert {:error, error} =
             ProfileRefresh.refresh("missing-provider", data_dir,
               source_data: source_data(),
               force: true
             )

    assert error.type == :missing_profile_provider
    refute File.exists?(Path.join(data_dir, "profiles.json"))
  end

  defp source_data do
    %{
      "anthropic" => %{
        "id" => "anthropic",
        "models" => %{
          "fixture-model" => %{
            "id" => "fixture-model",
            "name" => "Fixture model",
            "tool_call" => true,
            "limit" => %{"context" => 200_000, "output" => 4_096},
            "modalities" => %{"input" => ["text", "image"], "output" => ["text"]}
          }
        }
      }
    }
  end
end
